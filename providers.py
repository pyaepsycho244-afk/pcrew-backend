"""Provider abstraction. Phase 4 adds real classes (API-Football, Football-Data.org).
Keys are read from environment variables, never from frontend code."""
from abc import ABC, abstractmethod

class FootballProvider(ABC):
    @abstractmethod
    def fixtures(self, league: str, date_from: str, date_to: str) -> list[dict]: ...
    @abstractmethod
    def live(self) -> list[dict]: ...
    @abstractmethod
    def results(self, league: str, date_from: str, date_to: str) -> list[dict]: ...
    @abstractmethod
    def standings(self, league: str) -> list[dict]: ...
    @abstractmethod
    def team_stats(self, team_id: str) -> dict: ...
    @abstractmethod
    def events(self, fixture_id: str) -> list[dict]: ...
    @abstractmethod
    def lineups(self, fixture_id: str) -> dict: ...
    @abstractmethod
    def head_to_head(self, team_a: str, team_b: str) -> list[dict]: ...
